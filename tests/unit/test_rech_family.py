"""RECH (Nguyen et al. 2022) and DeepRGARCH / RealRECH (Liu et al. 2023).

Both models are built on the same promise: a recurrent component is added
*beside* a GARCH recursion, not on top of it, so that switching the network off
recovers the econometric baseline exactly. Every other claim in either paper
rests on that, so it is the first thing tested.
"""

from __future__ import annotations

import numpy as np
import pytest
import torch

from garchai.cells import GARCHCell
from garchai.core import ModelConfig, TrainConfig, set_seed
from garchai.structural import (
    RECH,
    DeepRGARCH,
    LSTMtGARCH,
    RealizedGARCH,
    RealRECH,
    SRNGARCH,
    SRNGJR,
    bounded_relu,
)

torch.set_default_dtype(torch.float64)


@pytest.fixture
def returns() -> torch.Tensor:
    set_seed(0)
    return torch.randn(300) * 0.9


@pytest.fixture
def realized() -> tuple[torch.Tensor, torch.Tensor]:
    """Returns plus a realized measure generated by the paper's own equations."""
    rng = np.random.default_rng(0)
    n = 400
    h = np.zeros(n)
    y = np.zeros(n)
    rv = np.zeros(n)
    h[0], rv[0] = 1.0, 1.0
    for t in range(1, n):
        h[t] = 0.05 + 0.35 * rv[t - 1] + 0.55 * h[t - 1]
        y[t] = np.sqrt(h[t]) * rng.standard_normal()
        z = y[t] / np.sqrt(h[t])
        rv[t] = max(
            -0.2 + 1.0 * h[t] + (-0.07 * z + 0.07 * (z**2 - 1)) + 0.4 * rng.standard_normal(),
            1e-4,
        )
    return torch.tensor(y[1:]), torch.tensor(rv[1:])


# --------------------------------------------------------------------------- #
# bounded ReLU and Theorem 1
# --------------------------------------------------------------------------- #
def test_bounded_relu_clamps_both_ends():
    x = torch.tensor([-5.0, -0.1, 0.0, 0.5, 1.0, 99.0])
    out = bounded_relu(x, upper=1.0)
    assert torch.equal(out, torch.tensor([0.0, 0.0, 0.0, 0.5, 1.0, 1.0]))


def test_omega_path_respects_theorem_1_bound(returns):
    r"""Theorem 1 needs ``omega_t <= M``; the bounded ReLU is what supplies it."""
    model = SRNGARCH(activation_bound=1.0)
    model.filter(returns)
    omega = model._last_paths["omega"]
    beta_0 = float(model.beta_0.detach())
    beta_1 = float(model.beta_1.detach())
    assert omega.min() >= beta_0 - 1e-12
    assert omega.max() <= beta_0 + beta_1 + 1e-12


def test_unbounded_activation_would_forfeit_the_bound(returns):
    """A larger bound genuinely permits a larger omega, so the bound is binding."""
    tight = SRNGARCH(activation_bound=0.1)
    loose = SRNGARCH(activation_bound=10.0)
    tight.filter(returns)
    loose.filter(returns)
    b0, b1 = float(tight.beta_0.detach()), float(tight.beta_1.detach())
    assert tight._last_paths["omega"].max() <= b0 + b1 * 0.1 + 1e-12


# --------------------------------------------------------------------------- #
# RECH
# --------------------------------------------------------------------------- #
def test_beta_1_zero_collapses_rech_to_plain_garch(returns):
    """The additive design's defining property."""
    model = RECH(implementation="paper", beta_1=0.0)
    rech_path, eps, _ = model.filter(returns)
    garch_path, _ = GARCHCell(0.05, 0.10, 0.85, init_method="sample").filter(eps)
    assert torch.allclose(rech_path, garch_path, atol=1e-12)


def test_recurrent_component_changes_the_path(returns):
    off, _, _ = RECH(implementation="paper", beta_1=0.0).filter(returns)
    on, _, _ = RECH(implementation="paper", beta_1=0.5).filter(returns)
    assert float((on - off).abs().max().detach()) > 1e-6


@pytest.mark.parametrize("factory", [SRNGARCH, SRNGJR, LSTMtGARCH])
def test_all_specifications_run_and_are_differentiable(factory, returns):
    model = factory()
    h, eps, _ = model.filter(returns)
    assert bool((h > 0).all()) and bool(torch.isfinite(h).all())
    model.negative_loglikelihood(returns).backward()
    assert all(
        p.grad is not None and torch.isfinite(p.grad).all() for p in model.parameters()
    )


def test_paper_and_official_code_presets_differ():
    """The authors say these are different models; garchai must not conflate them."""
    paper = RECH(implementation="paper")
    official = RECH(implementation="official_code")
    assert paper.network.kind == "srn"
    assert official.network.kind == "lstm"
    assert paper.config.distribution == "normal"
    assert official.config.distribution == "student-t"


def test_gjr_component_adds_a_leverage_parameter(returns):
    model = SRNGJR()
    assert "gamma" in model.garch_parameters()
    assert float(model.garch_parameters()["gamma"].detach()) >= 0.0


def test_recurrent_input_uses_signed_returns(returns):
    """x_t contains y_{t-1}, not y_{t-1}^2, so a symmetric component sees leverage."""
    model = SRNGARCH(beta_1=1.0)
    up, _, _ = model.filter(torch.tensor([1.0, 2.0, 0.0, 0.0, 0.0]))
    down, _, _ = model.filter(torch.tensor([1.0, -2.0, 0.0, 0.0, 0.0]))
    assert float((up - down).abs().max().detach()) > 0.0


def test_rech_fit_and_decomposition(returns):
    set_seed(0)
    model = SRNGARCH(config=ModelConfig(mean="zero", distribution="normal", scale=None))
    result = model.fit(returns.numpy(), TrainConfig(lr=0.05, max_epochs=40, patience=15))
    assert np.isfinite(result.loglikelihood)
    assert result.parameter_paths is not None and "omega" in result.parameter_paths

    parts = model.decomposition()
    assert parts["omega_t"] is not None
    assert np.allclose(
        parts["recurrent_contribution"], parts["omega_t"] - parts["beta_0"], atol=1e-12
    )
    assert np.all(parts["recurrent_contribution"] >= -1e-12)  # beta_1, h_t both >= 0


def test_rech_refuses_analytic_forecast(returns):
    model = SRNGARCH(config=ModelConfig(mean="zero", scale=None))
    model.fit(returns.numpy(), TrainConfig(max_epochs=3, patience=2))
    with pytest.raises(ValueError, match="no closed-form"):
        model.forecast(horizon=3, method="analytic")


def test_rech_rejects_unknown_components():
    with pytest.raises(ValueError, match="Unknown garch_component"):
        RECH(garch_component="aparch")
    with pytest.raises(ValueError, match="srn|lstm"):
        RECH(recurrent="transformer")


