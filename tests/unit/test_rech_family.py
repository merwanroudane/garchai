def test_deeprgarch_collapses_to_realized_garch(realized):
    y, rv = realized
    deep = DeepRGARCH(beta_1=0.0)
    baseline = RealizedGARCH(omega=float(deep.beta_0.detach()))
    with torch.no_grad():
        baseline.raw_gamma.copy_(deep.raw_gamma)
        baseline.raw_beta.copy_(deep.raw_beta)
    a, _, _ = deep._filter_with_rv(y, rv)
    b, _, _ = baseline._filter_with_rv(y, rv)
    assert torch.allclose(a, b, atol=1e-12)


def test_realrech_is_an_alias_for_deeprgarch():
    assert RealRECH is DeepRGARCH


def test_joint_likelihood_includes_the_measurement_equation(realized):
    """Without it, xi, phi, tau and sigma_u are unidentified."""
    y, rv = realized
    model = RealizedGARCH()
    before = float(model.joint_negative_loglikelihood(y, rv).detach())
    with torch.no_grad():
        model.raw_phi.fill_(-40.0)
    after = float(model.joint_negative_loglikelihood(y, rv).detach())
    assert abs(before - after) > 1.0


def test_leverage_function_is_centred():
    """E[tau(z)] = 0 under a standardised innovation keeps xi interpretable."""
    model = RealizedGARCH(tau1=-0.07, tau2=0.07)
    z = torch.randn(200_000)
    assert float(model.leverage(z).mean().detach()) == pytest.approx(0.0, abs=5e-3)


def test_realized_persistence_uses_beta_plus_gamma_phi(realized):
    """A shock reaches tomorrow's variance through the measurement equation."""
    y, rv = realized
    model = RealizedGARCH()
    model.fit(y, TrainConfig(max_epochs=5, patience=3), realized_variance=rv)
    p = model.result_.parameters
    assert model.result_.persistence == pytest.approx(
        p["beta"] + p["gamma"] * p["phi"], abs=1e-9
    )


@pytest.mark.slow
@pytest.mark.parametrize("factory", [RealizedGARCH, DeepRGARCH])
def test_realized_models_fit(realized, factory):
    y, rv = realized
    set_seed(0)
    model = factory()
    result = model.fit(
        y, TrainConfig(lr=0.05, max_epochs=60, patience=20), realized_variance=rv
    )
    assert np.isfinite(result.loglikelihood)
    assert np.all(result.conditional_variance > 0)


def test_realized_models_require_the_measure(realized):
    y, _ = realized
    with pytest.raises(ValueError, match="need a realized measure"):
        RealizedGARCH().fit(y)


def test_realized_models_validate_the_measure(realized):
    y, rv = realized
    with pytest.raises(ValueError, match="must align"):
        RealizedGARCH().fit(y, realized_variance=rv[:-5])
    with pytest.raises(ValueError, match="strictly positive"):
        RealizedGARCH().fit(y, realized_variance=torch.zeros_like(rv))


def test_filter_without_a_measure_is_refused():
    with pytest.raises(RuntimeError, match="realized measure is required"):
        RealizedGARCH().filter(torch.randn(20))


